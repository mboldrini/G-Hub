let currentLanguage = localStorage.getItem('language') || 'pt-BR';

// Traduzir chave
function t(key, ...args) {
  const value = i18n[currentLanguage]?.[key] ?? i18n['pt-BR'][key] ?? key;
  return typeof value === 'function' ? value(...args) : value;
}

// Aplicar idioma
function setLanguage(lang) {
  if (!i18n[lang]) {
    console.warn(`Language ${lang} not found, fallback to pt-BR`);
    lang = 'pt-BR';
  }
  currentLanguage = lang;
  localStorage.setItem('language', lang);
  translatePage();

  // Disparar evento customizado para outros módulos
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
}

// Traduzir todos os elementos da página
function translatePage() {
  // Traduzir textos
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });

  // Traduzir placeholders
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    el.placeholder = t(key);
  });

  // Traduzir titles
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.title = t(key);
  });

  // Atualizar display de idioma no header
  const langDisplay = document.getElementById('lang-display');
  if (langDisplay) {
    langDisplay.textContent = currentLanguage === 'pt-BR' ? 'PT' : 'EN';
  }

  // Atualizar atributo lang do HTML
  document.documentElement.lang = currentLanguage === 'pt-BR' ? 'pt-BR' : 'en-US';
}

// Exportar API global
window.i18nSystem = {
  t,
  setLanguage,
  translatePage,
  getCurrentLanguage: () => currentLanguage
};

// Alias curto para compatibilidade
window.t = t;
